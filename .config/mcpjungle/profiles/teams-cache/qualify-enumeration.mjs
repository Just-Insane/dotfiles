/** Offline qualification against a staged patched node_modules directory. */
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const root=resolve(process.argv[2]);
const load=p=>import(pathToFileURL(`${root}/${p}`).href);
const {queryConversations,queryConversationMessages}=await load('libzaungast/dist/query.js');
const db=new DatabaseSync(':memory:');
db.exec('create table conversations(id text,handle text,kind text,topic text,participant_names text,last_ts integer,msg_count integer); create table messages(conv_id text,id text,ts integer,is_system integer);');
for(let i=0;i<65;i++)db.prepare('insert into conversations values(?,?,?,?,?,?,?)').run(`c${String(i).padStart(3,'0')}`,`h${i}`,'channel','','',1234,0);
for(let i=0;i<205;i++)db.prepare('insert into messages values(?,?,?,?)').run('c000',String(i).padStart(4,'0'),1234,i%2);
const store={db};let cursor='';const ids=[];
do {const page=queryConversations(store,{n:30,includeEmpty:true,captureOrder:true,captureAfter:cursor});ids.push(...page.map(r=>r.id));cursor=page.at(-1)?.id??'';}while(cursor);
assert.equal(ids.length,65);assert.equal(new Set(ids).size,65);
const messageIds=[];cursor=undefined;
for(;;){const p=queryConversationMessages(store,'c000',{limit:30,cursor,captureIncludeSystem:true}).rows;messageIds.push(...p.map(r=>r.id));if(!p.length)break;cursor=`older:${p[0].ts}:${p[0].id}`;}
assert.equal(messageIds.length,205);assert.equal(new Set(messageIds).size,205);
assert.equal(queryConversationMessages(store,'c000',{limit:300}).rows.length,103);
assert.equal(queryConversations(store,{n:30}).length,0);
db.close();
const {Client}=await load('@modelcontextprotocol/sdk/dist/esm/client/index.js');
const {InMemoryTransport}=await load('@modelcontextprotocol/sdk/dist/esm/inMemory.js');
const {buildServer}=await load('zaungast/dist/server.js');
const {TOOLS}=await load('zaungast/dist/tools.js');
const view={meta:{schemaMatched:true,selfMri:'account',asOf:1234},conversations:{list:()=>[],get:()=>null}};
const server=buildServer({current:()=>view});const client=new Client({name:'offline-capture-qualification',version:'1'});
const [a,b]=InMemoryTransport.createLinkedPair();await server.connect(a);await client.connect(b);
const inventory=await client.listTools();assert.equal(inventory.tools.length,10);
const list=inventory.tools.find(t=>t.name==='list_conversations');assert.ok(list.inputSchema.properties.capture);
const legacy=await client.callTool({name:'list_conversations',arguments:{}});
assert.equal(legacy.content[0].text,TOOLS.find(t=>t.name==='list_conversations').run(view,{}, {tz:Intl.DateTimeFormat().resolvedOptions().timeZone,now:Date.now()}));
const page=await client.callTool({name:'list_conversations',arguments:{capture:true,expected_account_id:'account',n:1}});
assert.equal(page.structuredContent.schema,'teams-cache-conversations/v1');assert.equal(page.structuredContent.cache_complete,true);
assert.equal(page.structuredContent.provider_complete,false);
const missing=await client.callTool({name:'read_conversation',arguments:{capture:true,conversation:'c:old',expected_account_id:'account',expected_conversation_id:'gone'}});
assert.equal(missing.structuredContent.gaps[0].code,'CONVERSATION_NOT_CACHED');
await client.close();await server.close();
console.log('PASS: real SQLite keysets, tied timestamps, system rows, ten-tool SDK inventory, legacy text and structured transport');
